import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageManifest = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
const source = JSON.parse(
  await readFile(resolve(root, "config/release-capabilities.json"), "utf8")
);

if (typeof packageManifest.version !== "string" || packageManifest.version.trim() === "") {
  throw new Error("package.json requires a non-empty version");
}

const output = `// Generated by scripts/generate-capabilities.mjs. Do not edit.\n\n` +
  `export interface ReleaseCapabilities {\n` +
  `  product: "codex-progress-hud";\n` +
  `  buildVersion: string;\n` +
  `  protocol: { current: number; minimumClient: number; maximumClient: number };\n` +
  `  features: readonly string[];\n` +
  `}\n\n` +
  `export const RELEASE_CAPABILITIES: ReleaseCapabilities = ${JSON.stringify({
    ...source,
    buildVersion: packageManifest.version
  }, null, 2)} as const;\n\n` +
  `export function acceptsClientProtocol(protocol: number): boolean {\n` +
  `  return Number.isSafeInteger(protocol) &&\n` +
  `    protocol >= RELEASE_CAPABILITIES.protocol.minimumClient &&\n` +
  `    protocol <= RELEASE_CAPABILITIES.protocol.maximumClient;\n` +
  `}\n`;

const outputPath = resolve(root, "src/generated/capabilities.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
