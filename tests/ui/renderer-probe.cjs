const {app,BrowserWindow}=require('electron');
const {mkdtempSync}=require('node:fs');
const {tmpdir}=require('node:os');
const {join,resolve}=require('node:path');
const {pathToFileURL}=require('node:url');
app.setPath('userData',mkdtempSync(join(tmpdir(),'hud-render-test-')));
app.disableHardwareAcceleration();
const timeout=setTimeout(()=>app.exit(1),15000);
app.whenReady().then(async()=>{
  const window=new BrowserWindow({width:360,height:420,show:false,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});
  await window.loadFile(resolve(__dirname,'../fixtures/hud-dom.html'));
  const moduleUrl=pathToFileURL(resolve(__dirname,'../../dist/ui/conversation-renderer.js')).href;
  const clockUrl=pathToFileURL(resolve(__dirname,'../../dist/ui/display-clock.js')).href;
  const viewUrl=pathToFileURL(resolve(__dirname,'../../dist/ui/view-model.js')).href;
  const result=await window.webContents.executeJavaScript(`(async()=>{
    const {createConversationRenderer}=await import(${JSON.stringify(moduleUrl)});
    const root=document.querySelector('#tasks');
    const render=createConversationRenderer(root);
    const view=(key,title,percent)=>({key,taskId:key,title,statusLabel:'执行中',tone:'active',progressMode:percent===null?'indeterminate':'determinate',progressPercent:percent,etaLabel:'正在估算剩余时间',nameFreshness:'fresh'});
    render([view('a','同名聊天',20),view('b','同名聊天',null)]);
    if(root.children.length!==2)throw Error('row count');
    const first=root.children[0], second=root.children[1];
    render([view('a','<img src=x onerror=alert(1)>',40),view('b','同名聊天',null)]);
    if(root.children[0]!==first || root.children[1]!==second)throw Error('unstable nodes');
    if(root.querySelector('img'))throw Error('HTML injection');
    if(!first.textContent.includes('<img src=x onerror=alert(1)>'))throw Error('name changed');
    if(first.querySelector('[role=progressbar]').getAttribute('aria-valuenow')!=='40')throw Error('progress');
    if(second.querySelector('[role=progressbar]').hasAttribute('aria-valuenow'))throw Error('invented progress');
    const diagnosticView={...view('a','诊断测试',null),freshnessLabel:'估值更新于 2 分钟前',diagnosticLabel:'估时调用失败 · <img src=x onerror=alert(1)>'};
    render([diagnosticView,view('b','同名聊天',null)]);
    const details=first.querySelector('details');
    if(!details || details.hidden || details.open)throw Error('diagnostics not collapsed');
    details.open=true;
    render([{...diagnosticView,etaLabel:'00:01:59'},view('b','同名聊天',null)]);
    if(first.querySelector('details')!==details || !details.open)throw Error('diagnostics expansion lost on tick');
    if(first.querySelector('img'))throw Error('diagnostic HTML injection');
    if(!first.querySelector('.estimate-freshness').textContent.includes('2 分钟'))throw Error('freshness absent');
    render([view('b','同名聊天',null)]);
    if(root.children.length!==1 || root.children[0]!==second)throw Error('wrong removal');
    render(Array.from({length:32},(_,index)=>view(String(index),'长聊天名称'.repeat(40),index)));
    if(root.scrollHeight<=root.clientHeight)throw Error('missing scroll');
    const title=root.querySelector('.conversation-title');
    if(getComputedStyle(title).textOverflow!=='ellipsis' || title.scrollWidth<=title.clientWidth)throw Error('missing ellipsis');
    render([]);if(root.children.length!==0)throw Error('empty rows');
    const {createHudDisplayClock,startDisplayTicker}=await import(${JSON.stringify(clockUrl)});
    const {buildConversationViews}=await import(${JSON.stringify(viewUrl)});
    const clock=createHudDisplayClock();
    const goal={generation:1,estimateRevision:1,sampledAtMs:0,runtime:'running',status:'running',activeSeconds:0,
      prediction:{remainingSeconds:3600,errorPercent:30,observedActiveSeconds:0}};
    const row={conversationKey:'clock',task:{id:'clock'},eta:null,name:{value:'计时测试',freshness:'fresh'},goal};
    clock.accept({revision:1,rows:[row]},true);
    const draw=()=>{const frame=clock.read();render(buildConversationViews(frame.snapshot.rows,frame.elapsedSeconds));};
    draw();const clockNode=root.children[0];
    if(!clockNode.textContent.includes('01:00:00'))throw Error('initial countdown');
    const stop=startDisplayTicker(draw);
    try {
      await new Promise(resolve=>setTimeout(resolve,1200));
      if(root.children[0]!==clockNode || !clockNode.textContent.includes('00:59:59'))throw Error('local timer did not render');
      clock.disconnect();draw();const frozen=clockNode.textContent;
      await new Promise(resolve=>setTimeout(resolve,1200));
      if(clockNode.textContent!==frozen)throw Error('disconnected countdown advanced');
      clock.accept({revision:2,rows:[{...row,goal:{...goal,runtime:'waiting',status:'waiting'}}]},false);
      draw();await new Promise(resolve=>setTimeout(resolve,1200));
      if(!clockNode.textContent.includes('01:00:00') || !clockNode.textContent.includes('等待用户'))throw Error('waiting countdown advanced');
      clock.accept({revision:3,rows:[]},false);draw();
      if(root.children.length)throw Error('completed row retained');
    } finally {stop();}
    return {domPassed:true,countdownPassed:true};
  })()`);
  console.log(JSON.stringify(result));window.destroy();clearTimeout(timeout);app.exit(0);
}).catch(error=>{console.error(error.message);clearTimeout(timeout);app.exit(1);});
